/**
 * Clamps traceability confidence into the [0.50, 0.65] range appropriate
 * for TGW translations (complex topology with many advisory gaps).
 */
function clampConfidence(
  traceability: ReturnType<typeof makeTraceability>,
): ReturnType<typeof makeTraceability> {
  const raw = traceability.confidence;
  // Guard NaN/Infinity before clamping — Math.max(0.50, NaN) === NaN
  const safeRaw = typeof raw === 'number' && isFinite(raw) ? raw : 0.50;
  const clamped = Math.round(Math.min(0.65, Math.max(0.50, safeRaw)) * 100) / 100;
  return { ...traceability, confidence: clamped };
}

