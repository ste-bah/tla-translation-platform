/**
 * Extracts the VPC ID from the context resource, defaulting to 'main'.
 */
function extractVpcId(attrs: Record<string, unknown>): string {
  const vpcId = attrs['vpc_id'];
  return typeof vpcId === 'string' && vpcId.length > 0 ? vpcId : 'main';
}

/**
 * Extracts the first subnet ID, or returns undefined.
 */
function extractFirstSubnet(attrs: Record<string, unknown>): string | undefined {
  const ids = attrs['subnet_ids'];
  if (Array.isArray(ids) && ids.length > 0 && typeof ids[0] === 'string') {
    return ids[0];
  }
  return undefined;
}

/**
 * Detects whether the service_name references a cross-account endpoint
 * (contains a 12-digit AWS account ID).
 */
function isCrossAccount(attrs: Record<string, unknown>): boolean {
  const sn = attrs['service_name'];
  return typeof sn === 'string' && CROSS_ACCOUNT_RE.test(sn);
}

