/**
 * Translates aws_vpc_endpoint or aws_vpc_endpoint_service to the target
 * provider's private connectivity primitives.
 *
 * - Interface endpoints -> real resources (Azure Private Endpoint / GCP PSC)
 * - Gateway endpoints -> advisory (no equivalent)
 * - Endpoint services (producer) -> advisory
 * - Cross-account endpoints -> blocker
 * - Unknown sourceType -> safe advisory fallback (no throw)
 */
export function translatePrivateLink(ctx: TranslationContext): EngineResult {
  const { resource } = ctx;
  const attrs = resource.attributes as Record<string, unknown>;

  // Producer path: aws_vpc_endpoint_service
  if (resource.sourceType === 'aws_vpc_endpoint_service') {
    return translateProducerAdvisory(ctx);
  }

  // Safe fallback for any sourceType other than the two known ones.
  // This prevents silent misclassification when an unexpected type arrives.
  if (resource.sourceType !== 'aws_vpc_endpoint') {
    return {
      translated: [],
      findings: [
        createFinding(
          resource.id,
          'warning',
          'PRIVATELINK_UNKNOWN_SOURCE_TYPE',
          `Unknown sourceType '${String(resource.sourceType ?? '')}' for privatelink-mapping; ` +
            'no translation emitted — review resource type and rerun',
        ),
      ],
    };
  }

  // Consumer paths: aws_vpc_endpoint
  const endpointType = attrs['vpc_endpoint_type'];

  // Gateway endpoints (S3/DynamoDB) -> advisory
  if (endpointType === 'Gateway') {
    return translateGatewayAdvisory(ctx);
  }

  // Cross-account blocker check (Interface endpoints only)
  if (isCrossAccount(attrs)) {
    return translateCrossAccountBlocker(ctx);
  }

  // Interface endpoint -> real resources
  if (ctx.targetProvider === 'azure') {
    return translateConsumerAzure(ctx);
  }
  return translateConsumerGcp(ctx);
}
