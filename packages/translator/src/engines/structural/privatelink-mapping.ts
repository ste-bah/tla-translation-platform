/**
 * Clamps traceability confidence to [0.45, 0.60] — PrivateLink translations
 * have significant behavioral gaps across providers.
 */
function clampConfidence(
  traceability: ReturnType<typeof makeTraceability>,
): ReturnType<typeof makeTraceability> {
  const raw = traceability.confidence;
  const safeRaw = typeof raw === 'number' && isFinite(raw) ? raw : 0.45;
  const clamped =
    Math.round(Math.min(0.60, Math.max(0.45, safeRaw)) * 100) / 100;
  return { ...traceability, confidence: clamped };
}

