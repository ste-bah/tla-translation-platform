/**
 * Azure Terraform code generator.
 *
 * Stateless — construct and call {@link generate} with resources and options.
 */
export class AzureCodeGenerator {
  /**
   * Generates a set of `.tf` files from translated resources.
   *
   * @param resources - Translated Azure resources from the engine pipeline.
   * @param options   - Generation options (all optional with sensible defaults).
   * @returns A Map of filename → file content.
   */
  generate(
    resources: readonly TranslatedResource[],
    options?: AzureGenOptions,
  ): GeneratedFiles {
    const resolved: Required<AzureGenOptions> = {
      sourceRegion: options?.sourceRegion ?? 'us-east-1',
      resourceGroupName: options?.resourceGroupName ?? 'main',
      subscriptionIdVar: options?.subscriptionIdVar ?? '',
      environment: options?.environment ?? 'dev',
      emitComments: options?.emitComments ?? true,
      sortKeys: options?.sortKeys ?? true,
      emitResourceGroup: options?.emitResourceGroup ?? true,
    };

    logger.info({ resourceCount: resources.length, region: resolved.sourceRegion }, 'Generating Azure HCL');

    const files: GeneratedFiles = new Map();

    files.set('main.tf', generateMainTf(resources, resolved));
    files.set('providers.tf', generateProvidersTf(resolved));
    files.set('terraform.tf', generateTerraformTf());
    files.set('variables.tf', generateVariablesTf(resolved));
    files.set('outputs.tf', generateOutputsTf(resolved));

    logger.debug({ files: files.size }, 'Azure codegen complete');

    return files;
  }
}
