/**
 * Converts an arbitrary JS value (from TranslatedResource.attributes) into
 * an {@link HclValue} using the heuristics described in the architecture.
 *
 * @internal Exported for unit-test access only. Not part of the public API
 *           contract -- prefer {@link AzureCodeGenerator.generate} for
 *           external consumers.
 * @param value     - The value to convert.
 * @param parentKey - The attribute key that holds this value (used for
 *                    block-vs-map disambiguation).
 */
export function convertValue(value: unknown, parentKey?: string): HclValue {
  if (value === null || value === undefined) {
    return literal(null);
  }
  if (typeof value === 'boolean') {
    return literal(value);
  }
  if (typeof value === 'number') {
    return literal(value);
  }
  if (typeof value === 'string') {
    // Terraform interpolation: ${...} → expression
    const interpMatch = /^\$\{(.+)\}$/.exec(value);
    if (interpMatch) {
      return expr(interpMatch[1]!);
    }
    return literal(value);
  }

  if (Array.isArray(value)) {
    // Arrays of objects where the parent key is a block key → blocks
    if (
      value.length > 0 &&
      value.every((v) => typeof v === 'object' && v !== null && !Array.isArray(v)) &&
      parentKey !== undefined &&
      AZURE_BLOCK_KEYS.has(parentKey)
    ) {
      const blockEntries: HclMapEntry[] = value.map((item) => ({
        key: parentKey,
        value: convertObject(item as Record<string, unknown>, true),
      }));
      return { kind: 'blocks', blocks: blockEntries };
    }
    // Regular list
    return list(value.map((v) => convertValue(v)));
  }

  if (typeof value === 'object') {
    return convertObject(value as Record<string, unknown>, isBlockKey(parentKey));
  }

  // Fallback — stringify
  return literal(String(value));
}

/**
 * Converts a plain object to either an HclMap or HclBlock.
 */
function convertObject(
  obj: Record<string, unknown>,
  asBlock: boolean,
): HclMap | HclBlock {
  const entries: HclMapEntry[] = Object.keys(obj).map((k) => ({
    key: k,
    value: convertValue(obj[k], k),
  }));

  if (asBlock) {
    return { kind: 'block', body: entries };
  }
  return { kind: 'map', entries };
}

/**
 * Determines whether a key should produce a block (not a map).
 * `tags` is always a map; keys in AZURE_BLOCK_KEYS are blocks.
 */
function isBlockKey(key: string | undefined): boolean {
  if (key === undefined) return false;
  if (key === 'tags') return false;
  return AZURE_BLOCK_KEYS.has(key);
}

