/**
 * Azure Terraform code generator.
 *
 * Takes an array of {@link TranslatedResource} objects (produced by the
 * translation engines) and emits a set of `.tf` files ready for
 * `terraform init && terraform plan`.
 *
 * Output files:
 * - `main.tf`       — resource blocks sorted by (targetType, targetName)
 * - `providers.tf`  — `provider "azurerm"` with `features {}`
 * - `terraform.tf`  — `required_providers` block
 * - `variables.tf`  — location, resource_group_name, environment, subscription_id
 * - `outputs.tf`    — resource_group_name, resource_group_id
 *
 * @module codegen/azure-codegen
 * @generated by code-generator (TASK-TRANS-006)
 */

import type { TranslatedResource } from '@tla/shared';
import { createComponentLogger } from '@tla/shared';

import {
  literal,
  expr,
  hclMap,
  block,
  list,
  writeResourceBlock,
  writeProviderBlock,
  writeTerraformBlock,
  writeVariableBlock,
  writeOutputBlock,
} from './hcl-writer.js';
import type { HclValue, HclMapEntry, HclMap, HclBlock } from './hcl-writer.js';
import { resolveAzureRegion } from './azure/region-mapping.js';
import { sanitizeAzureName } from './azure/naming.js';

const logger = createComponentLogger('azure-codegen');

// ---------------------------------------------------------------------------
// Options
// ---------------------------------------------------------------------------

/**
 * Options for the Azure code generator.
 */
export interface AzureGenOptions {
  /** AWS source region for location mapping. Default `'us-east-1'`. */
  readonly sourceRegion?: string;
  /** Terraform name for the resource group. Default `'main'`. */
  readonly resourceGroupName?: string;
  /** If set, adds `subscription_id` to the provider block. */
  readonly subscriptionIdVar?: string;
  /** Environment tag value. Default `'dev'`. */
  readonly environment?: string;
  /** Emit `# Source:` comments above resource blocks. Default `true`. */
  readonly emitComments?: boolean;
  /** Sort attributes alphabetically within each resource. Default `true`. */
  readonly sortKeys?: boolean;
  /** Emit an `azurerm_resource_group` block in main.tf. Default `true`. */
  readonly emitResourceGroup?: boolean;
}

