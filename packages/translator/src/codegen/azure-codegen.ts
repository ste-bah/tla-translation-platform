// Resource conversion
// ---------------------------------------------------------------------------

/**
 * Converts a TranslatedResource's attributes into an array of HclMapEntry.
 */
function resourceToEntries(
  resource: TranslatedResource,
  sortKeys: boolean,
): HclMapEntry[] {
  const attrs = resource.attributes as Record<string, unknown>;
  const keys = sortKeys
    ? Object.keys(attrs).sort((a, b) => a.localeCompare(b))
    : Object.keys(attrs);

  return keys.map((k) => ({ key: k, value: convertValue(attrs[k], k) }));
}

// ---------------------------------------------------------------------------
// File generators
// ---------------------------------------------------------------------------

function generateMainTf(
  resources: readonly TranslatedResource[],
  options: Required<AzureGenOptions>,
): string {
  const sorted = [...resources].sort((a, b) => {
    const typeCmp = a.targetType.localeCompare(b.targetType);
    return typeCmp !== 0 ? typeCmp : a.targetName.localeCompare(b.targetName);
  });

  const blocks: string[] = [];

  // Optional resource group
  if (options.emitResourceGroup) {
    const rgBody: HclMapEntry[] = [
      { key: 'name', value: expr('var.resource_group_name') },
      { key: 'location', value: expr('var.location') },
      { key: 'tags', value: hclMap({
        environment: expr('var.environment'),
      }) },
    ];
    blocks.push(
      writeResourceBlock(
        'azurerm_resource_group',
        options.resourceGroupName,
        rgBody,
        { comment: 'Resource Group', sortKeys: options.sortKeys },
      ),
    );
  }

  for (const resource of sorted) {
    const entries = resourceToEntries(resource, options.sortKeys);
    const comment = options.emitComments
      ? `Source: ${resource.traceability.sourceType} (${resource.sourceId}), engine: ${resource.traceability.engineUsed}, confidence: ${resource.traceability.confidence}`
      : undefined;

    blocks.push(
      writeResourceBlock(
        resource.targetType,
        sanitizeAzureName(
          extractTypeShort(resource.targetType),
          resource.targetName,
        ),
        entries,
        { comment, sortKeys: options.sortKeys },
      ),
    );
  }

  if (blocks.length === 0) {
    return '# No resources translated\n';
  }

  return blocks.join('\n\n') + '\n';
}

function generateProvidersTf(options: Required<AzureGenOptions>): string {
  const body: HclMapEntry[] = [
    { key: 'features', value: block({}) },
  ];

  if (options.subscriptionIdVar) {
    body.push({
      key: 'subscription_id',
      value: expr(`var.${options.subscriptionIdVar}`),
    });
  }

  return writeProviderBlock('azurerm', body) + '\n';
}

function generateTerraformTf(): string {
  const azurermProvider: HclMapEntry[] = [
    {
      key: 'azurerm',
      value: block({
        source: literal('hashicorp/azurerm'),
        version: literal('~> 3.0'),
      }),
    },
  ];

  const body: HclMapEntry[] = [
    {
      key: 'required_providers',
      value: { kind: 'block' as const, body: azurermProvider },
    },
  ];

  return writeTerraformBlock(body) + '\n';
}

function generateVariablesTf(
  options: Required<AzureGenOptions>,
): string {
  const azureRegion = resolveAzureRegion(options.sourceRegion);

  const blocks: string[] = [
    writeVariableBlock('location', {
      description: 'Azure region for all resources',
      type: 'string',
      defaultValue: literal(azureRegion),
    }),
    writeVariableBlock('resource_group_name', {
      description: 'Name of the resource group',
      type: 'string',
      defaultValue: literal(`rg-${options.environment}`),
    }),
    writeVariableBlock('environment', {
      description: 'Deployment environment',
      type: 'string',
      defaultValue: literal(options.environment),
    }),
    writeVariableBlock('subscription_id', {
      description: 'Azure subscription ID',
      type: 'string',
      sensitive: true,
    }),
  ];

  return blocks.join('\n\n') + '\n';
}

function generateOutputsTf(
  options: Required<AzureGenOptions>,
): string {
  if (!options.emitResourceGroup) {
    return '# No outputs (resource group emission disabled)\n';
  }

  const blocks: string[] = [
    writeOutputBlock('resource_group_name', {
      description: 'The name of the resource group',
      value: expr(`azurerm_resource_group.${options.resourceGroupName}.name`),
    }),
    writeOutputBlock('resource_group_id', {
      description: 'The ID of the resource group',
      value: expr(`azurerm_resource_group.${options.resourceGroupName}.id`),
    }),
  ];

  return blocks.join('\n\n') + '\n';
}

