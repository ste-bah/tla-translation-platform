/**
 * Compiles a portable resource into native target-provider Terraform resources.
 *
 * Unsupported attribute combinations are returned as explicit findings with
 * severity 'warning' or 'info' — they are never silently dropped.
 *
 * @param resource - The portable resource descriptor (validated via Zod).
 * @param target   - The target cloud provider.
 * @returns         Translated native resources + diagnostic findings.
 *
 * @throws {Error} If the combination of resource_type and target is not
 *   supported (should not happen for valid inputs; included as a safety net).
 */
export function compilePortableResource(
  resource: PortableResource,
  target: CloudProvider,
): PortableCompileResult {
  switch (resource.resource_type) {
    case 'cloud_object_storage': {
      let r: PortableCompileResult;
      switch (target) {
        case 'aws':   r = compileObjectStorageAws(resource); break;
        case 'azure': r = compileObjectStorageAzure(resource); break;
        case 'gcp':   r = compileObjectStorageGcp(resource); break;
      }
      return applyOverrides(r!, resource, target);
    }

    case 'cloud_container_registry': {
      let r: PortableCompileResult;
      switch (target) {
        case 'aws':   r = compileContainerRegistryAws(resource); break;
        case 'azure': r = compileContainerRegistryAzure(resource); break;
        case 'gcp':   r = compileContainerRegistryGcp(resource); break;
      }
      return applyOverrides(r!, resource, target);
    }

    case 'cloud_cache_redis': {
      let r: PortableCompileResult;
      switch (target) {
        case 'aws':   r = compileRedisAws(resource); break;
        case 'azure': r = compileRedisAzure(resource); break;
        case 'gcp':   r = compileRedisGcp(resource); break;
      }
      return applyOverrides(r!, resource, target);
    }
  }

  // TypeScript exhaustiveness guard — should be unreachable at runtime.
  const exhaustive = resource as { resource_type: string };
  throw new Error(
    `compilePortableResource: unsupported resource_type '${exhaustive.resource_type}' for target '${target}'`,
  );
}
