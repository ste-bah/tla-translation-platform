/**
 * Portable resource compiler — translates cloud_* resources into native
 * provider-specific Terraform resources.
 *
 * Supported portable types:
 *   cloud_object_storage      → aws_s3_bucket / azurerm_storage_account + container / google_storage_bucket
 *   cloud_container_registry  → aws_ecr_repository / azurerm_container_registry / google_artifact_registry_repository
 *   cloud_cache_redis         → aws_elasticache_replication_group / azurerm_redis_cache / google_redis_instance
 *
 * Unsupported attributes are surfaced as explicit error findings — they are
 * NEVER silently dropped.
 *
 * @module provider/portable-compiler
 * @generated by code-generator (TASK-MCP-006)
 */

import type { CloudProvider, TranslatedResource, TranslationFinding } from '@tla/shared';
import type {
  PortableResource,
  CloudObjectStorage,
  CloudContainerRegistry,
  CloudCacheRedis,
} from '@tla/shared';
import { createFinding } from '../engines/direct/attribute-transformer.js';
import {
  REGION_MAP,
  NODE_TYPE_SKU_MAP,
} from '../engines/direct/attribute-transformer.js';

