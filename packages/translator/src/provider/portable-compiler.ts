function compileObjectStorageAws(res: CloudObjectStorage): PortableCompileResult {
  const attrs: Record<string, unknown> = {
    bucket: res.name,
  };

  const findings: TranslationFinding[] = [];

  if (res.versioning_enabled === true) {
    attrs['versioning'] = { enabled: true };
  }

  if (res.encryption) {
    if (res.encryption.kms_key_ref) {
      attrs['server_side_encryption_configuration'] = {
        rule: {
          apply_server_side_encryption_by_default: {
            sse_algorithm: 'aws:kms',
            kms_master_key_id: res.encryption.kms_key_ref,
          },
        },
      };
    } else if (res.encryption.enabled) {
      attrs['server_side_encryption_configuration'] = {
        rule: {
          apply_server_side_encryption_by_default: {
            sse_algorithm: 'AES256',
          },
        },
      };
    }
  }

  if (res.tags) {
    attrs['tags'] = convertTags(res.tags, 'aws');
  }

  const translated: TranslatedResource[] = [
    {
      targetType: 'aws_s3_bucket',
      targetName: res.name,
      attributes: attrs,
      sourceId: `portable:cloud_object_storage:${res.name}`,
      traceability: makePortableTraceability(res.name, 'cloud_object_storage', 'aws'),
    },
  ];

  return { translated, findings };
}

function compileObjectStorageAzure(res: CloudObjectStorage): PortableCompileResult {
  const findings: TranslationFinding[] = [];
  const saName = normalizeNameForProvider(res.name, 'azure');

  const accountAttrs: Record<string, unknown> = {
    account_kind: 'StorageV2',
    account_replication_type: 'LRS',
    account_tier: 'Standard',
    location: defaultRegion('azure'),
    name: saName,
  };

  if (res.versioning_enabled === true) {
    accountAttrs['blob_properties'] = { versioning_enabled: true };
  }

  if (res.encryption?.kms_key_ref) {
    accountAttrs['customer_managed_key'] = {
      key_vault_key_id: res.encryption.kms_key_ref,
    };
  }

  if (res.tags) {
    accountAttrs['tags'] = convertTags(res.tags, 'azure');
  }

  const containerAttrs: Record<string, unknown> = {
    container_access_type: 'private',
    name: res.name,
    storage_account_name: saName,
  };

  const traceability = makePortableTraceability(res.name, 'cloud_object_storage', 'azure');

  const translated: TranslatedResource[] = [
    {
      targetType: 'azurerm_storage_account',
      targetName: `${res.name}_account`,
      attributes: accountAttrs,
      sourceId: `portable:cloud_object_storage:${res.name}`,
      traceability,
    },
    {
      targetType: 'azurerm_storage_container',
      targetName: `${res.name}_container`,
      attributes: containerAttrs,
      sourceId: `portable:cloud_object_storage:${res.name}`,
      traceability,
    },
  ];

  return { translated, findings };
}

function compileObjectStorageGcp(res: CloudObjectStorage): PortableCompileResult {
  const findings: TranslationFinding[] = [];

  const gcpAttrs: Record<string, unknown> = {
    location: defaultRegion('gcp'),
    name: res.name,
    storage_class: 'STANDARD',
  };

  if (res.versioning_enabled === true) {
    gcpAttrs['versioning'] = { enabled: true };
  }

  if (res.encryption?.kms_key_ref) {
    gcpAttrs['encryption'] = { default_kms_key_name: res.encryption.kms_key_ref };
  }

  if (res.tags) {
    gcpAttrs['labels'] = convertTags(res.tags, 'gcp');
  }

  const translated: TranslatedResource[] = [
    {
      targetType: 'google_storage_bucket',
      targetName: res.name,
      attributes: gcpAttrs,
      sourceId: `portable:cloud_object_storage:${res.name}`,
      traceability: makePortableTraceability(res.name, 'cloud_object_storage', 'gcp'),
    },
  ];

  return { translated, findings };
}

