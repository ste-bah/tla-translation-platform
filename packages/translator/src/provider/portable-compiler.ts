/** Maps portable size to the closest node type for SKU lookup. */
const SIZE_TO_NODE_TYPE: Record<string, string> = {
  xs: 'cache.t3.micro',
  sm: 'cache.t3.medium',
  md: 'cache.m5.large',
  lg: 'cache.r5.large',
  xl: 'cache.r5.2xlarge',
};

function parseAzureSku(sku: string): { sku_name: string; family: string; capacity: number } {
  const parts = sku.split('_');
  const tier = parts[0] ?? 'Standard';
  const sizeCode = parts[1] ?? 'C1';
  const family = sizeCode.charAt(0);
  const capacity = parseInt(sizeCode.slice(1), 10) || 1;
  return { sku_name: tier, family, capacity };
}

function parseGcpTier(tierStr: string): { tier: string; memory_size_gb: number } {
  const isHa = tierStr.includes('HA');
  const gbMatch = tierStr.match(/(\d+)GB$/);
  const memorySizeGb = gbMatch ? parseInt(gbMatch[1]!, 10) : 1;
  return { tier: isHa ? 'STANDARD_HA' : 'BASIC', memory_size_gb: memorySizeGb };
}

