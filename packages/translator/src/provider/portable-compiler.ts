/**
 * Applies `provider_overrides` from the portable resource onto compiled
 * translated resources.
 *
 * Behaviour:
 *   - If `provider_overrides[target]` exists, every key in that map is
 *     shallow-merged into each translated resource's attributes.  One
 *     `PORTABLE_OVERRIDE_APPLIED` info finding is emitted per applied key.
 *   - If `provider_overrides` contains a key for a *different* provider
 *     (i.e. not the active target), a `PORTABLE_OVERRIDE_IGNORED` warning
 *     finding is emitted for that provider key so the caller is aware of
 *     the ignored configuration.
 *   - AWS overrides are not supported in `provider_overrides` (the field
 *     only accepts 'azure' and 'gcp') so no ignored-warning is needed for
 *     'aws' targets.
 *
 * @param result   - The compile result produced by the per-provider compilers.
 * @param resource - The original portable resource (may carry provider_overrides).
 * @param target   - The active target cloud provider.
 * @returns A new {@link PortableCompileResult} with overrides applied and
 *   findings appended.
 */
function applyOverrides(
  result: PortableCompileResult,
  resource: PortableResource,
  target: CloudProvider,
): PortableCompileResult {
  const overrides = (resource as { provider_overrides?: { azure?: Record<string, unknown>; gcp?: Record<string, unknown> } }).provider_overrides;
  if (!overrides) {
    return result;
  }

  const extraFindings: TranslationFinding[] = [];
  const sourceId = `portable:${resource.resource_type}:${resource.name}`;

  // Emit warnings for overrides targeting the wrong provider.
  const otherProviders = (['azure', 'gcp'] as const).filter((p) => p !== target);
  for (const other of otherProviders) {
    if (overrides[other] && Object.keys(overrides[other]!).length > 0) {
      extraFindings.push(
        createFinding(
          sourceId,
          'warning',
          'PORTABLE_OVERRIDE_IGNORED',
          `provider_overrides.${other} is ignored because the active target is '${target}'`,
        ),
      );
    }
  }

  // Apply overrides for the active target provider (azure or gcp only).
  const activeOverrides =
    (target === 'azure' || target === 'gcp') ? overrides[target] : undefined;

  if (!activeOverrides || Object.keys(activeOverrides).length === 0) {
    return {
      translated: result.translated,
      findings: [...result.findings, ...extraFindings],
    };
  }

  // Shallow-merge each override key into every translated resource's attributes.
  const mergedTranslated = result.translated.map((tr) => ({
    ...tr,
    attributes: { ...(tr.attributes as Record<string, unknown>), ...activeOverrides },
  }));

  // Emit one info finding per applied key.
  for (const key of Object.keys(activeOverrides)) {
    extraFindings.push(
      createFinding(
        sourceId,
        'info',
        'PORTABLE_OVERRIDE_APPLIED',
        `provider_overrides.${target}.${key} applied to translated resource(s)`,
      ),
    );
  }

  return {
    translated: mergedTranslated,
    findings: [...result.findings, ...extraFindings],
  };
}

