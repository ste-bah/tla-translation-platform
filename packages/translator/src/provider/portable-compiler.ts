/**
 * Baseline traceability for portable-compiled resources.
 */
function makePortableTraceability(
  resourceName: string,
  resourceType: string,
  target: CloudProvider,
): TranslatedResource['traceability'] {
  return {
    sourceId: `portable:${resourceType}:${resourceName}`,
    sourceType: resourceType,
    registryEntryId: null,
    mappingType: 'direct',
    confidence: 0.9,
    engineUsed: `portable-compiler/${target}`,
  };
}

/**
 * Normalises a resource name for the target provider.
 * - AWS / GCP: allow alphanumeric, hyphens, underscores
 * - Azure: strip non-alphanumeric (storage accounts require ^[a-z0-9]{3,24})
 */
function normalizeNameForProvider(name: string, target: CloudProvider): string {
  if (target === 'azure') {
    return name.replace(/[^a-z0-9]/g, '').slice(0, 24);
  }
  return name;
}

/**
 * Converts portable tags to provider label format.
 * GCP labels must be lowercase [a-z0-9_-].
 */
function convertTags(
  tags: Record<string, string>,
  target: CloudProvider,
): Record<string, string> {
  if (target === 'gcp') {
    const result: Record<string, string> = {};
    for (const [k, v] of Object.entries(tags)) {
      result[k.toLowerCase().replace(/[^a-z0-9_-]/g, '_')] = v;
    }
    return result;
  }
  return { ...tags };
}

/**
 * Resolves a default AWS region to the target provider region string.
 */
function defaultRegion(target: CloudProvider): string {
  const entry = REGION_MAP.get('us-east-1');
  if (!entry) return 'us-east-1';
  return target === 'azure' ? entry.azure : entry.gcp;
}

